def pop(a, b):
    # Берем числа по модулю на случай, если они отрицательные
    a = abs(a)
    b = abs(b)
    
    while b != 0:
        # a получает старое значение b, а b получает остаток от деления a на b
        a, b = b, a % b
        
    return a

