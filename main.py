n = int(input("Введите высоту треугольника: "))

# Начинаем с самой верхней строчки
row = [1]

for i in range(n):
    # Выводим текущую строку, разделяя числа пробелами
    print(" ".join(map(str, row)))
    
    # Формируем следующую строку:
    # 1. Добавляем нули по краям: [0] + row + [0]
    # 2. Складываем соседние элементы: (0+1), (1+2), (2+1), (1+0)
    row = [row[j] + row[j+1] for j in range(len(row) - 1)]
    row = [1] + row + [1]  # Или так: row = [1] + [row[k] + row[k+1] for k in range(len(row)-1)] + [1]